    {POSITION_LATITUDE_KEY} DOUBLE,
    {POSITION_LONGITUDE_KEY} DOUBLE,
    {POSITION_BEARING_KEY} DOUBLE,
    {POSITION_ODOMETER_KEY} DOUBLE,
